public class Transporte {

    // encapsulamento
    private String tipo;
    private double valorDolar;

    
    public String getTipo() {
        return tipo;
    }

    public void setTipo (String tipo){
        this.tipo = tipo;
    }

    public double getValorDolar(){
        return valorDolar;
    }

    public void setValorDolar(double valorDolar) {
        this.valorDolar = valorDolar;
    }
}